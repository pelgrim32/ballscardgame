// Builds dist/worker.js: the game's rules engine (copied from index.html) + server.js.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(here, '..', 'index.html'), 'utf8');
const a = html.indexOf('/* ================= ENGINE ================= */');
const b = html.indexOf('/* ================= HELPERS ================= */');
if (a < 0 || b < 0) throw new Error('engine markers not found in index.html');
let engine = html.slice(a, b)
  .replace(/^applyLang\(\);\s*$/m, '')
  .replace(/^let lang=.*$/m, "let lang='en';");
if (!/let lang='en';/.test(engine)) throw new Error('could not replace the language line');
engine += "\nfunction label(c){ return rank(c)==='X'?'Joker':rank(c)+SYM[suit(c)]; }\n";
const server = readFileSync(join(here, 'server.js'), 'utf8');
mkdirSync(join(here, 'dist'), { recursive: true });
writeFileSync(join(here, 'dist', 'worker.js'), `/* generated by build.mjs — do not edit */\n${engine}\n${server}`);
console.log('dist/worker.js written', engine.length + server.length, 'bytes');
